/**
 * Виджет Нейроядра — только для администраторов.
 *
 * Данные виджета закрыты на сервере: `plugins/neuroCore/viget.neuro.php` не
 * отдаёт ничего, если у пользователя нет прав администратора. Здесь закрывается
 * видимость — то, что видит сотрудник:
 *
 *   - строка виджета в «Мои настройки» → «Виджеты»: без неё включить виджет
 *     нельзя, и он не появится в списке у того, кому не предназначен;
 *   - плитка на рабочем столе: если виджет был включён, когда сотрудник был
 *     администратором, а потом права сняли, плитка уходит вместе со строкой.
 *
 * Почему так, а не правкой страниц: список виджетов собирают
 * `content/ajax/user.settings.php` и `content/desktop/dt.wigets.php` — это файлы
 * дистрибутива, и правки в них теряются при обновлении CRM. Своих прав в карте
 * виджетов (`cash/map.vigets.castom.json`) тоже нет: там есть только признак
 * модуля, который проверяется по аккаунту, а не по пользователю.
 *
 * Скрипт подключается только тем, кому скрывать нечего... точнее — только тем,
 * кому скрывать НАДО: для администратора страница не меняется вообще.
 */

$(function () {

	'use strict';

	if (typeof NeuroCoreViget === 'undefined' || !NeuroCoreViget.hide) {
		return;
	}

	var KEY = 'neuro_core';

	/**
	 * Убирает плитку виджета с рабочего стола.
	 *
	 * Делается до того, как рабочий стол начнёт загружать содержимое плиток:
	 * удалённого элемента в списке уже нет, поэтому лишнего запроса не будет.
	 */
	function hideTile() {

		$('div.viget[data-id="' + KEY + '"]').remove();

	}

	/**
	 * Убирает строку виджета из «Мои настройки» → «Виджеты».
	 *
	 * Диалог приходит отдельным запросом, поэтому кроме первой проверки нужен
	 * наблюдатель: строка появляется позже, чем выполняется этот код. Вместе со
	 * строкой уходит и hidden-поле `order[]` — значит, сохранение настроек не
	 * вернёт выключенный виджет в список.
	 */
	function hideRow() {

		$('tr#v-' + KEY).remove();

	}

	hideTile();
	hideRow();

	if (typeof MutationObserver === 'function') {

		var observer = new MutationObserver(function () {
			hideRow();
		});

		observer.observe(document.body, {childList: true, subtree: true});

	}

});
